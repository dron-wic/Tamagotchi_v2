"""Convert a PNG into a raw RGB565 sprite or a C array.

Transparent and near-magenta pixels become the chroma key 0xF81F.
The pet loader skips that value, so the character can have a soft outline
cut out of a flat background.

Raw file (drop onto the device flash filesystem):
    python tools/png_to_rgb565.py art.png data/pet/0.rgb

C array for a UI icon:
    python tools/png_to_rgb565.py icon.png --header src/assets/my_icon.c --name img_my

Recommended pet frame: about 160x180, facing forward, magenta background,
feet near the bottom. Hard edges survive the conversion better than
feathered transparency.
"""

import argparse
import struct
import sys

try:
    from PIL import Image
except ImportError:
    sys.exit("Install Pillow: pip install pillow")

CHROMA = 0xF81F


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def is_key(r, g, b, a):
    if a < 24:
        return True
    return r > 235 and b > 235 and g < 40


def convert(path):
    im = Image.open(path).convert("RGBA")
    pixels = []
    for r, g, b, a in im.getdata():
        pixels.append(CHROMA if is_key(r, g, b, a) else rgb565(r, g, b))
    return im.size[0], im.size[1], pixels


def write_raw(path, w, h, pixels):
    with open(path, "wb") as f:
        f.write(b"R565")
        f.write(struct.pack("<HH", w, h))
        f.write(struct.pack("<%dH" % len(pixels), *pixels))


def write_header(path, name, w, h, pixels):
    lines = [
        "/* Generated by tools/png_to_rgb565.py */",
        "#include \"lvgl.h\"",
        "",
        "static const uint16_t %s_map[] = {" % name,
    ]
    for i in range(0, len(pixels), 12):
        chunk = ", ".join("0x%04x" % p for p in pixels[i : i + 12])
        lines.append("    %s," % chunk)
    lines += [
        "};",
        "const lv_img_dsc_t %s = {" % name,
        "    .header.cf = LV_IMG_CF_TRUE_COLOR_CHROMA_KEYED,",
        "    .header.always_zero = 0,",
        "    .header.reserved = 0,",
        "    .header.w = %d," % w,
        "    .header.h = %d," % h,
        "    .data_size = %d," % (w * h * 2),
        "    .data = (const uint8_t *)%s_map," % name,
        "};",
        "",
    ]
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))


def main():
    parser = argparse.ArgumentParser(description="PNG to RGB565 for the pet project")
    parser.add_argument("png")
    parser.add_argument("raw", nargs="?", help="output .rgb file")
    parser.add_argument("--header", help="also write a C array")
    parser.add_argument("--name", default="img_custom")
    args = parser.parse_args()
    w, h, pixels = convert(args.png)
    if args.raw:
        write_raw(args.raw, w, h, pixels)
        print("wrote %s (%dx%d)" % (args.raw, w, h))
    if args.header:
        write_header(args.header, args.name, w, h, pixels)
        print("wrote %s" % args.header)
    if not args.raw and not args.header:
        sys.exit("Pass a .rgb path and/or --header")


if __name__ == "__main__":
    main()
