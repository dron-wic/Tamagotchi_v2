"""Generate the Cyrillic UI font and small RGB565 icons.

Run from the project root:
    python tools/gen_assets.py
"""

import os
from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
# Tahoma stays crisp at 16 px on a small TFT; Comic Sans AA mush
# made Cyrillic words like "Покормить" look like one smear.
FONT_PATH = r"C:\Windows\Fonts\tahoma.ttf"
FONT_BOLD = r"C:\Windows\Fonts\tahomabd.ttf"
FONT_BPP = 1
# Extra whole pixels of advance so adjacent glyphs do not touch.
ADV_PAD_PX = 1


def rgb565(r, g, b):
    return ((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3)


def isqrt(n):
    if n <= 0:
        return 0
    x = n
    y = (x + 1) // 2
    while y < x:
        x = y
        y = (x + n // x) // 2
    return x


def pack_glyph(rows, bpp=FONT_BPP):
    bits = []
    levels = (1 << bpp) - 1
    for row in rows:
        for a in row:
            if bpp == 1:
                v = 1 if a >= 140 else 0
            else:
                v = (a * levels + 127) // 255
                if v > levels:
                    v = levels
            for shift in range(bpp - 1, -1, -1):
                bits.append((v >> shift) & 1)
    while len(bits) % 8:
        bits.append(0)
    out = []
    for i in range(0, len(bits), 8):
        byte = 0
        for b in bits[i : i + 8]:
            byte = (byte << 1) | b
        out.append(byte)
    return out


def render_glyph(font, ch, ascent):
    if ch == " ":
        adv = max(1, int(round(font.getlength(" ") * 16)))
        return [], 0, 0, 0, 0, adv
    canvas_w, canvas_h = 128, ascent + 48
    img = Image.new("L", (canvas_w, canvas_h), 0)
    draw = ImageDraw.Draw(img)
    draw.text((8, ascent), ch, font=font, fill=255, anchor="ls")
    bbox = img.getbbox()
    adv = max(1, int(round(font.getlength(ch) * 16)))
    if not bbox:
        return [], 0, 0, 0, 0, adv
    x0, y0, x1, y1 = bbox
    crop = img.crop(bbox)
    box_w, box_h = crop.size
    ofs_x = x0 - 8
    ofs_y = ascent - y1
    if adv < (box_w + max(0, ofs_x)) * 16:
        adv = (box_w + max(0, ofs_x)) * 16
    adv += ADV_PAD_PX * 16
    pixels = list(crop.getdata())
    rows = [pixels[i * box_w : (i + 1) * box_w] for i in range(box_h)]
    return rows, box_w, box_h, ofs_x, ofs_y, adv


def build_font(font_file, size, symbol):
    font = ImageFont.truetype(font_file, size)
    ascent, descent = font.getmetrics()
    chars = [chr(c) for c in range(32, 127)]
    chars += [chr(c) for c in range(0x410, 0x450)]
    chars += ["Ё", "ё"]
    glyphs = []
    bitmap = []
    max_box = 0
    for ch in chars:
        rows, bw, bh, ox, oy, adv = render_glyph(font, ch, ascent)
        max_box = max(max_box, bw, bh, abs(ox), abs(oy))
        if bw > 255 or bh > 255 or not -128 <= ox <= 127 or not -128 <= oy <= 127:
            raise SystemExit("glyph overflow for %r box %s ofs %s,%s" % (ch, (bw, bh), ox, oy))
        if adv > 4095:
            adv = 4095
        packed = pack_glyph(rows, FONT_BPP) if bw and bh else []
        glyphs.append((ch, len(bitmap), adv, bw, bh, ox, oy))
        bitmap.extend(packed)
    line_height = ascent + descent
    base_line = descent
    return {
        "symbol": symbol,
        "size": size,
        "line_height": line_height,
        "base_line": base_line,
        "glyphs": glyphs,
        "bitmap": bitmap,
        "max_box": max_box,
        "bpp": FONT_BPP,
    }


def emit_font(fonts, path):
    lines = []
    w = lines.append
    w("/* Generated by tools/gen_assets.py — Cyrillic UI font for LVGL 8.4 */")
    w("#include \"lvgl.h\"")
    w("")
    for font in fonts:
        sym = font["symbol"]
        w("static const uint8_t %s_bitmap[] = {" % sym)
        bm = font["bitmap"]
        for i in range(0, len(bm), 16):
            chunk = ", ".join("0x%02x" % b for b in bm[i : i + 16])
            w("    %s," % chunk)
        w("};")
        w("")
        w("static const lv_font_fmt_txt_glyph_dsc_t %s_dsc[] = {" % sym)
        w("    {.bitmap_index = 0, .adv_w = 0, .box_w = 0, .box_h = 0, .ofs_x = 0, .ofs_y = 0},")
        for ch, index, adv, bw, bh, ox, oy in font["glyphs"]:
            w(
                "    {.bitmap_index = %d, .adv_w = %d, .box_w = %d, .box_h = %d, .ofs_x = %d, .ofs_y = %d}, /* U+%04X */"
                % (index, adv, bw, bh, ox, oy, ord(ch))
            )
        w("};")
        w("")
        w("static const lv_font_fmt_txt_cmap_t %s_cmaps[] = {" % sym)
        # ASCII 32..126 -> glyph 1, Cyrillic 0x410..0x44F -> glyph 96, Yo, yo
        w("    {.range_start = 32, .range_length = 95, .glyph_id_start = 1,")
        w("     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},")
        w("    {.range_start = 0x410, .range_length = 64, .glyph_id_start = 96,")
        w("     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},")
        w("    {.range_start = 0x401, .range_length = 1, .glyph_id_start = 160,")
        w("     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},")
        w("    {.range_start = 0x451, .range_length = 1, .glyph_id_start = 161,")
        w("     .unicode_list = NULL, .glyph_id_ofs_list = NULL, .list_length = 0, .type = LV_FONT_FMT_TXT_CMAP_FORMAT0_TINY},")
        w("};")
        w("")
        w("static lv_font_fmt_txt_glyph_cache_t %s_cache;" % sym)
        w("static const lv_font_fmt_txt_dsc_t %s_fmt = {" % sym)
        w("    .glyph_bitmap = %s_bitmap," % sym)
        w("    .glyph_dsc = %s_dsc," % sym)
        w("    .cmaps = %s_cmaps," % sym)
        w("    .kern_dsc = NULL,")
        w("    .kern_scale = 0,")
        w("    .cmap_num = 4,")
        w("    .bpp = %d," % font["bpp"])
        w("    .kern_classes = 0,")
        w("    .bitmap_format = LV_FONT_FMT_TXT_PLAIN,")
        w("    .cache = &%s_cache," % sym)
        w("};")
        w("")
        w("const lv_font_t %s = {" % sym)
        w("    .get_glyph_dsc = lv_font_get_glyph_dsc_fmt_txt,")
        w("    .get_glyph_bitmap = lv_font_get_bitmap_fmt_txt,")
        w("    .line_height = %d," % font["line_height"])
        w("    .base_line = %d," % font["base_line"])
        w("    .subpx = LV_FONT_SUBPX_NONE,")
        w("    .underline_position = -1,")
        w("    .underline_thickness = 1,")
        w("    .dsc = &%s_fmt," % sym)
        w("    .fallback = NULL,")
        w("#if LV_USE_USER_DATA")
        w("    .user_data = NULL,")
        w("#endif")
        w("};")
        w("")
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")


def new_icon():
    return [0x07E0] * (32 * 32)


def setp(buf, x, y, c):
    if 0 <= x < 32 and 0 <= y < 32:
        buf[y * 32 + x] = c


def disc(buf, cx, cy, r, c):
    r2 = r * r
    for y in range(32):
        dy = y - cy
        for x in range(32):
            dx = x - cx
            if dx * dx + dy * dy <= r2:
                buf[y * 32 + x] = c


def rect(buf, x, y, w, h, c):
    for yy in range(y, y + h):
        for xx in range(x, x + w):
            setp(buf, xx, yy, c)


def icon_cookie():
    b = new_icon()
    dough = rgb565(210, 150, 88)
    chip = rgb565(86, 52, 34)
    hi = rgb565(240, 210, 168)
    rim = rgb565(176, 118, 64)
    disc(b, 16, 16, 12, rim)
    disc(b, 16, 16, 11, dough)
    disc(b, 12, 12, 4, hi)
    for p in ((11, 14), (18, 12), (15, 18), (20, 19), (12, 20)):
        disc(b, p[0], p[1], 2, chip)
    return b


def icon_cake():
    b = new_icon()
    cream = rgb565(255, 236, 220)
    icing = rgb565(255, 150, 170)
    sponge = rgb565(255, 190, 130)
    cherry = rgb565(220, 70, 90)
    disc(b, 16, 21, 11, sponge)
    rect(b, 6, 17, 20, 5, icing)
    rect(b, 6, 13, 20, 5, cream)
    disc(b, 16, 11, 3, cherry)
    disc(b, 15, 10, 1, rgb565(255, 210, 210))
    return b


def icon_apple():
    # Friendly candy-apple: warm red (not blood), soft highlight,
    # teal leaf far from chroma-key green 0x00FF00.
    b = new_icon()
    body = rgb565(236, 92, 78)
    shade = rgb565(198, 58, 54)
    hi = rgb565(255, 214, 176)
    leaf = rgb565(48, 168, 128)
    stem = rgb565(110, 74, 42)
    disc(b, 16, 19, 10, shade)
    disc(b, 16, 18, 9, body)
    disc(b, 12, 14, 3, hi)
    disc(b, 11, 13, 1, rgb565(255, 240, 220))
    rect(b, 15, 6, 2, 5, stem)
    # Leaf as a small oval, not a hard green blob.
    for dy in range(-2, 3):
        for dx in range(-4, 5):
            if dx * dx + dy * dy * 3 <= 14:
                setp(b, 20 + dx, 9 + dy, leaf)
    setp(b, 18, 9, rgb565(90, 196, 150))
    return b


def icon_milk():
    b = new_icon()
    white = rgb565(252, 250, 248)
    blue = rgb565(110, 168, 236)
    outline = rgb565(78, 128, 196)
    stripe = rgb565(255, 214, 96)
    rect(b, 11, 7, 10, 4, blue)
    rect(b, 10, 11, 12, 15, white)
    rect(b, 10, 11, 12, 2, outline)
    rect(b, 10, 24, 12, 2, outline)
    rect(b, 10, 11, 2, 15, outline)
    rect(b, 20, 11, 2, 15, outline)
    rect(b, 13, 16, 6, 2, stripe)
    return b


def icon_candy():
    b = new_icon()
    wrap = rgb565(255, 140, 170)
    wrap2 = rgb565(120, 190, 255)
    candy = rgb565(255, 236, 140)
    stripe = rgb565(255, 170, 120)
    disc(b, 7, 16, 5, wrap)
    disc(b, 24, 16, 5, wrap2)
    rect(b, 10, 11, 12, 10, candy)
    rect(b, 14, 11, 3, 10, stripe)
    return b


def icon_coin():
    b = new_icon()
    gold = rgb565(242, 184, 40)
    dark = rgb565(196, 130, 20)
    hi = rgb565(255, 230, 140)
    disc(b, 16, 16, 12, dark)
    disc(b, 16, 16, 10, gold)
    disc(b, 12, 12, 3, hi)
    rect(b, 14, 10, 3, 12, rgb565(255, 248, 220))
    return b


def icon_heart():
    b = new_icon()
    pink = rgb565(255, 80, 140)
    hi = rgb565(255, 180, 210)
    disc(b, 11, 13, 7, pink)
    disc(b, 20, 13, 7, pink)
    for y in range(12, 28):
        t = (y - 12) / 16.0
        half = int(14 * (1.0 - t))
        for x in range(16 - half, 16 + half):
            setp(b, x, y, pink)
    disc(b, 10, 11, 2, hi)
    return b


def emit_icons(path_c, path_h):
    icons = [
        ("img_cookie", icon_cookie()),
        ("img_cake", icon_cake()),
        ("img_apple", icon_apple()),
        ("img_milk", icon_milk()),
        ("img_candy", icon_candy()),
        ("img_coin", icon_coin()),
        ("img_heart", icon_heart()),
    ]
    lines = []
    w = lines.append
    w("/* Generated by tools/gen_assets.py — 32x32 RGB565, green chroma key */")
    w("#include \"lvgl.h\"")
    w("")
    for name, pixels in icons:
        w("static const uint16_t %s_map[] = {" % name)
        for i in range(0, len(pixels), 12):
            chunk = ", ".join("0x%04x" % p for p in pixels[i : i + 12])
            w("    %s," % chunk)
        w("};")
        w("const lv_img_dsc_t %s = {" % name)
        w("    .header.cf = LV_IMG_CF_TRUE_COLOR_CHROMA_KEYED,")
        w("    .header.always_zero = 0,")
        w("    .header.reserved = 0,")
        w("    .header.w = 32,")
        w("    .header.h = 32,")
        w("    .data_size = 32 * 32 * 2,")
        w("    .data = (const uint8_t *)%s_map," % name)
        w("};")
        w("")
    with open(path_c, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines) + "\n")
    hlines = [
        "#pragma once",
        "#include \"lvgl.h\"",
        "#ifdef __cplusplus",
        'extern "C" {',
        "#endif",
    ]
    for name, _ in icons:
        hlines.append("extern const lv_img_dsc_t %s;" % name)
    hlines += ["#ifdef __cplusplus", "}", "#endif", ""]
    with open(path_h, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(hlines) + "\n")


def main():
    fonts = [
        build_font(FONT_PATH, 16, "font_ru_16"),
        build_font(FONT_BOLD, 22, "font_ru_22"),
    ]
    for font in fonts:
        print(
            font["symbol"],
            "glyphs",
            len(font["glyphs"]),
            "bitmap",
            len(font["bitmap"]),
            "line",
            font["line_height"],
            "base",
            font["base_line"],
            "maxbox",
            font["max_box"],
        )
    emit_font(fonts, os.path.join(ROOT, "src", "ui", "font_ru.c"))
    os.makedirs(os.path.join(ROOT, "src", "assets"), exist_ok=True)
    emit_icons(
        os.path.join(ROOT, "src", "assets", "icons.c"),
        os.path.join(ROOT, "src", "assets", "icons.h"),
    )
    print("wrote font and icons")


if __name__ == "__main__":
    main()
